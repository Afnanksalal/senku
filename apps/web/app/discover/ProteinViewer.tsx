'use client';
import { useEffect, useRef, useState } from 'react';
import { api } from '../../lib/api';

export default function ProteinViewer({ pdbId }: { pdbId: string }) {
  const host = useRef<HTMLDivElement>(null);
  const reset = useRef<() => void>(() => undefined);
  const [state, setState] = useState<'loading' | 'ready' | 'failed'>('loading');
  useEffect(() => {
    let disposed = false;
    let cleanup: (() => void) | undefined;
    const abort = new AbortController();
    (async () => {
      const response = await api<Response>(`/v1/structures/${encodeURIComponent(pdbId)}/file`, { auth: true, raw: true, signal: abort.signal });
      const cif = await response.text();
      const [{ PluginContext }, { DefaultPluginSpec }] = await Promise.all([import('molstar/lib/commonjs/mol-plugin/context'), import('molstar/lib/commonjs/mol-plugin/spec')]);
      if (disposed) return;
      const plugin = new PluginContext(DefaultPluginSpec());
      cleanup = () => plugin.dispose();
      await plugin.init();
      if (disposed || !host.current) return;
      if (!(await plugin.mountAsync(host.current))) throw new Error('Viewer unavailable');
      plugin.canvas3d?.setProps({ renderer: { backgroundColor: 0xf7faf6 as never } });
      const data = await plugin.builders.data.rawData({ data: cif, label: `PDB ${pdbId}` });
      const trajectory = await plugin.builders.structure.parseTrajectory(data, 'mmcif');
      await plugin.builders.structure.hierarchy.applyPreset(trajectory, 'default');
      if (disposed) return;
      reset.current = () => plugin.managers.camera.reset();
      setState('ready');
    })().catch(() => { if (!disposed) setState('failed'); });
    return () => { disposed = true; abort.abort(); cleanup?.(); reset.current = () => undefined; };
  }, [pdbId]);
  return <div className="stack snug">
    <div className="mol-view" style={{ height: 'clamp(300px, 50vh, 520px)' }} role="img" aria-label={`Deposited 3D structure ${pdbId}. Drag to rotate and scroll to zoom. Structure metadata is available above.`}>
      <div ref={host} style={{ position: 'absolute', inset: 0 }} />
      {state !== 'ready' && <p role="status" style={{ position: 'absolute', inset: 0, display: 'grid', placeItems: 'center', padding: '1rem', textAlign: 'center' }}>{state === 'loading' ? 'Loading deposited coordinates...' : 'The structure preview could not load. You can still inspect the source record or download its coordinates.'}</p>}
    </div>
    {state === 'ready' && <div className="row"><button className="btn quiet small" onClick={() => reset.current()}>Reset view</button><p className="faint">Drag to rotate. Scroll or pinch to zoom. Coordinates are retrieved from RCSB, not generated by AI.</p></div>}
  </div>;
}
